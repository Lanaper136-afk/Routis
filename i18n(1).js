function getLang() {
  const savedLang = safeGetItem("lang", null);
  if (savedLang === "fr" || savedLang === "en") return savedLang;

  const browserLanguages = Array.isArray(navigator.languages) && navigator.languages.length
    ? navigator.languages
    : [navigator.language];

  const preferredLanguage = browserLanguages.find((lang) => {
    const normalized = String(lang || "").toLowerCase();
    return normalized.startsWith("en") || normalized.startsWith("fr");
  });

  return String(preferredLanguage || "").toLowerCase().startsWith("en") ? "en" : "fr";
}

function setLang(lang) {
  safeSetItem("lang", lang);
}

function t(key, vars) {
  const dict = I18N[getLang()] || I18N.fr;
  let str = dict[key] !== undefined ? dict[key] : (I18N.fr[key] !== undefined ? I18N.fr[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(`{${k}}`, vars[k]);
    });
  }
  return str;
}

function signField(sign, field) {
  if (getLang() === "en" && sign.en && sign.en[field] !== undefined) return sign.en[field];
  return sign[field];
}

function famLabel(family) {
  return t(`chip_${family}`);
}

function applyStaticTranslations() {
  document.documentElement.lang = getLang();
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  document.querySelectorAll(".lang-option").forEach((el) => {
    el.classList.toggle("active", el.dataset.lang === getLang());
  });
  const switcher = document.querySelector("#lang-switcher");
  if (switcher) switcher.setAttribute("aria-label", t("lang_switch_label"));
  const toggleHint = document.querySelector("#toggle-hint");
  const learnedToggleBtn = document.querySelector("#learned-toggle");
  if (toggleHint && learnedToggleBtn) {
    toggleHint.textContent = learnedToggleBtn.getAttribute("aria-expanded") === "true" ? t("toggle_hide") : t("toggle_show");
  }
}
